-- Ejecutar en SQL*Plus conectado como DOCENTEMARCHA:  @01_ampliar_bd.sql
-- Es seguro repetirlo: ignora lo que ya existe.
SET SERVEROUTPUT ON
DECLARE
  PROCEDURE ej(s VARCHAR2) IS BEGIN EXECUTE IMMEDIATE s;
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE NOT IN (-955,-1430,-2275,-2260,-2261,-1442,-1408) THEN
      DBMS_OUTPUT.PUT_LINE('ERROR '||SQLERRM||' -> '||SUBSTR(s,1,70)); END IF;
  END;
BEGIN
  -- Columnas nuevas en tablas existentes
  ej(q'[ALTER TABLE PERSONAS ADD (PROGRAMA VARCHAR2(100), SEMESTRE NUMBER(2))]');
  ej(q'[ALTER TABLE INSTITUCIONES ADD (CIUDAD VARCHAR2(80), CONVENIO_ESTADO VARCHAR2(20), CONVENIO_INICIO DATE, CONVENIO_FIN DATE)]');
  ej(q'[ALTER TABLE VISITAS ADD (FORTALEZAS VARCHAR2(500), ASPECTOS_MEJORAR VARCHAR2(500))]');

  -- Catalogo de practicas (lo que define el coordinador)
  ej(q'[CREATE TABLE CATALOGO_PRACTICAS (ID_CATALOGO NUMBER(10) PRIMARY KEY, NOMBRE VARCHAR2(120) NOT NULL,
        PROGRAMA VARCHAR2(100), SEMESTRE NUMBER(2), HORAS_REQUERIDAS NUMBER(5) DEFAULT 0 NOT NULL,
        FECHA_INICIO DATE, FECHA_FIN DATE, DESCRIPCION VARCHAR2(500), ESTADO VARCHAR2(20) DEFAULT 'ACTIVA' NOT NULL)]');
  ej(q'[CREATE TABLE CATALOGO_INSTITUCIONES (ID_CATALOGO NUMBER(10) REFERENCES CATALOGO_PRACTICAS, 
        ID_INSTITUCION NUMBER(10) REFERENCES INSTITUCIONES, PRIMARY KEY (ID_CATALOGO, ID_INSTITUCION))]');
  ej(q'[CREATE TABLE GRUPOS (ID_GRUPO NUMBER(10) PRIMARY KEY, NOMBRE VARCHAR2(100) NOT NULL,
        ID_CATALOGO NUMBER(10) REFERENCES CATALOGO_PRACTICAS, ID_INSTITUCION NUMBER(10) REFERENCES INSTITUCIONES,
        ID_DOCENTE NUMBER(10) REFERENCES PERSONAS, JORNADA VARCHAR2(30), HORARIO VARCHAR2(100), CUPO NUMBER(4),
        FECHA_INICIO DATE, FECHA_FIN DATE)]');
  ej(q'[CREATE TABLE ASIGNACIONES (ID_ASIGNACION NUMBER(10) PRIMARY KEY, ID_ESTUDIANTE NUMBER(10) NOT NULL REFERENCES PERSONAS,
        ID_GRUPO NUMBER(10) NOT NULL REFERENCES GRUPOS, ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
        FECHA_ENVIO DATE DEFAULT SYSDATE, FECHA_DECISION DATE)]');
  ej(q'[CREATE TABLE RUBRICAS (ID_RUBRICA NUMBER(10) PRIMARY KEY, ID_DOCENTE NUMBER(10) NOT NULL REFERENCES PERSONAS,
        NOMBRE VARCHAR2(120) NOT NULL, CRITERIOS CLOB)]');
  ej(q'[CREATE TABLE CUESTIONARIOS (ID_CUESTIONARIO NUMBER(10) PRIMARY KEY, ID_DOCENTE NUMBER(10) NOT NULL REFERENCES PERSONAS,
        NOMBRE VARCHAR2(120) NOT NULL, PREGUNTAS CLOB)]');
  ej(q'[CREATE TABLE DESEMPENOS (ID_DESEMPENO NUMBER(10) PRIMARY KEY, ID_PRACTICA NUMBER(10) NOT NULL REFERENCES PRACTICAS,
        FECHA DATE DEFAULT SYSDATE, CALIFICACION NUMBER(4,2), COMENTARIOS VARCHAR2(1000), ESTADO VARCHAR2(20) DEFAULT 'REGISTRADO')]');
  ej(q'[CREATE TABLE CONFIRMACIONES (ID_CONFIRMACION NUMBER(10) PRIMARY KEY, ID_PRACTICA NUMBER(10) NOT NULL REFERENCES PRACTICAS,
        FECHA DATE DEFAULT SYSDATE, DETALLE VARCHAR2(500), ESTADO VARCHAR2(20) DEFAULT 'CONFIRMADA')]');
  ej(q'[CREATE TABLE CONFIG_PROGRAMA (CLAVE VARCHAR2(40) PRIMARY KEY, VALOR NUMBER(8,2) NOT NULL)]');

  -- La practica de cada estudiante apunta al catalogo y al grupo
  ej(q'[ALTER TABLE PRACTICAS ADD (ID_CATALOGO NUMBER(10) REFERENCES CATALOGO_PRACTICAS, ID_GRUPO NUMBER(10) REFERENCES GRUPOS)]');

  -- Secuencias nuevas
  FOR s IN (SELECT column_value n FROM TABLE(sys.odcivarchar2list('CATALOGO_PRACTICAS','GRUPOS','ASIGNACIONES',
            'RUBRICAS','CUESTIONARIOS','DESEMPENOS','CONFIRMACIONES'))) LOOP
    ej('CREATE SEQUENCE SEQ_'||s.n||' START WITH 1 INCREMENT BY 1 NOCACHE');
  END LOOP;

  -- Roles que usa la plataforma (no duplica si ya hay uno parecido)
  FOR r IN (SELECT column_value n FROM TABLE(sys.odcivarchar2list('ESTUDIANTE','DOCENTE','COORDINADOR','DIRECTOR'))) LOOP
    INSERT INTO ROLES (ID_ROL, NOMBRE, DESCRIPCION)
      SELECT SEQ_ROLES.NEXTVAL, r.n, 'Rol '||LOWER(r.n) FROM dual
      WHERE NOT EXISTS (SELECT 1 FROM ROLES WHERE UPPER(NOMBRE) LIKE r.n||'%');
  END LOOP;

  -- Metas por defecto del programa
  FOR c IN (SELECT 'metaHoras' k, 80 v FROM dual UNION ALL SELECT 'metaNota',3.5 FROM dual UNION ALL
            SELECT 'metaAprobacion',90 FROM dual UNION ALL SELECT 'metaConvenios',100 FROM dual UNION ALL
            SELECT 'metaVisitas',2 FROM dual UNION ALL SELECT 'metaAsistencia',90 FROM dual) LOOP
    INSERT INTO CONFIG_PROGRAMA SELECT c.k, c.v FROM dual WHERE NOT EXISTS (SELECT 1 FROM CONFIG_PROGRAMA WHERE CLAVE=c.k);
  END LOOP;
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('Listo: base de datos ampliada.');
END;
/
